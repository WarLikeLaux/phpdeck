**Режимы:**
- **Асинхронная** — master не ждёт реплики. **Быстро**, но при падении master свежие транзакции **могут потеряться**.
- **Полусинхронная** — master ждёт **подтверждения** от хотя бы одной реплики. Компромисс.
- **Синхронная** — ждёт подтверждения **всех**. **Медленно**, но без потери данных.

